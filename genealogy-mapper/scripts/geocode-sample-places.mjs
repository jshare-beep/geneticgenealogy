// One-time (or re-run-after-a-fresh-export) prep step for the "walkthrough with sample
// data" onboarding path. The sample data (sampleTreeAData.js/sampleTreeBData.js/
// sampleTreeCData.js/sampleTreeDData.js) is GEDCOM-derived data with only place
// TEXT, same as any fresh import - so loading it triggers the app's normal live
// geocoding pass, throttled at Nominatim's 1 request/second, before more than a
// handful of dots show up on the map.
//
// This script geocodes every unique place string across all four sample branches
// ONCE, offline, respecting the same throttle the app itself uses, and writes the
// results to samplePlaceCache.json - which sampleData.js then reads at build time to
// bake real lat/lng/precision directly onto every birth/death/event record. The
// walkthrough becomes instant and fully offline-safe: no network call, no wait,
// regardless of the browser's own geocode cache (private window included).
//
// Run with: node scripts/geocode-sample-places.mjs
// IMPORTANT: run this from a normal terminal on your own machine, not through an AI
// coding assistant's sandboxed environment - Nominatim rate-limits by IP, and a
// sandbox's shared outbound IP can already be tapped out from other unrelated traffic
// (confirmed on 2026-08-26: even a single isolated request came back 429 from that
// environment, while the exact same request works fine from a normal connection).
// Takes 10-20 minutes for ~900 places, unattended - just let it run to completion.
// Re-run whenever the *Data.js files are regenerated from a fresh GEDCOM export - it
// only looks up places not already in the cache, so a re-run after a small data change
// is fast.

import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const syncDir = path.join(__dirname, '..', 'js', 'sync');
// A plain .js module, not .json - this app has no bundler and loads everything as
// browser ES modules directly (see index.html), so sampleData.js can just `import` this
// like any other data file instead of needing a fetch() + JSON.parse() at runtime.
const cachePath = path.join(syncDir, 'samplePlaceCache.js');

function serializeCache(cache) {
  const lines = Object.entries(cache)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${value ? JSON.stringify(value) : 'null'},`);
  return (
    `// Generated by scripts/geocode-sample-places.mjs - do not hand-edit. Keyed by\n` +
    `// normalized (trimmed, lowercased) place text, same convention as the app's own\n` +
    `// runtime geocode cache (see geocodePlace in js/geocode/geocode.js). A null value\n` +
    `// means Nominatim had no match for that place text at all, not that it's unchecked.\n` +
    `export const SAMPLE_PLACE_CACHE = {\n${lines.join('\n')}\n};\n`
  );
}

// 1.1s (Nominatim's documented 1 req/sec policy plus a small buffer) turned out not to
// be enough headroom in practice - confirmed 2026-08-27: at that pace, most requests
// came back 429 rather than a real result, not just an occasional one. 3s is more
// conservative; the per-request retry/backoff below is the real safety net regardless.
const MIN_INTERVAL_MS = 3000;
const CITY_ADDRESS_TYPES = new Set(['city', 'town', 'village', 'hamlet', 'suburb', 'municipality', 'borough', 'township', 'city_district', 'neighbourhood']);

function classifyPrecision(result) {
  const rank = result?.place_rank;
  if (typeof rank === 'number') return rank >= 16 ? 'city' : 'broad';
  return CITY_ADDRESS_TYPES.has(result?.addresstype) ? 'city' : 'broad';
}

function normalize(place) {
  return String(place || '').trim().toLowerCase();
}

async function collectPlaces() {
  const places = new Set();
  const { TREE_A_PEOPLE } = await import(path.join(syncDir, 'sampleTreeAData.js'));
  const { TREE_B_PEOPLE } = await import(path.join(syncDir, 'sampleTreeBData.js'));
  const { TREE_C_PEOPLE } = await import(path.join(syncDir, 'sampleTreeCData.js'));
  const { TREE_D_PEOPLE } = await import(path.join(syncDir, 'sampleTreeDData.js'));
  for (const people of [TREE_A_PEOPLE, TREE_B_PEOPLE, TREE_C_PEOPLE, TREE_D_PEOPLE]) {
    for (const p of people) {
      if (p.birthPlace) places.add(p.birthPlace.trim());
      if (p.deathPlace) places.add(p.deathPlace.trim());
      for (const e of p.events || []) {
        if (e.place) places.add(e.place.trim());
      }
    }
  }
  return [...places];
}

async function loadExistingCache() {
  try {
    const { SAMPLE_PLACE_CACHE } = await import(cachePath);
    return { ...SAMPLE_PLACE_CACHE };
  } catch {
    return {};
  }
}

let lastCallAt = 0;
// A 429 gets its own retry-with-backoff, separate from every other failure - the
// caller (main, below) treats anything that ends up throwing as "still unknown, leave
// it out of the cache for a future run to retry", but only AFTER this has already
// given Nominatim several increasingly patient chances to actually answer, rather than
// giving up (and risking main() mistaking that for a genuine no-match) on the very
// first rate-limit response.
async function throttledFetch(url, attempt = 0) {
  const wait = Math.max(0, MIN_INTERVAL_MS - (Date.now() - lastCallAt));
  if (wait > 0) await new Promise((resolve) => setTimeout(resolve, wait));
  lastCallAt = Date.now();
  const res = await fetch(url, {
    headers: {
      Accept: 'application/json',
      // Nominatim's usage policy requires a real identifying User-Agent for
      // unattended/scripted use - this is a local one-off dev prep script, not a
      // deployed service, so a plain descriptive string is enough.
      'User-Agent': 'GenealogyMapper-SampleDataPrep/1.0 (local dev script, one-time sample data geocoding)',
    },
  });
  if (res.status === 429) {
    if (attempt >= 5) throw new Error('rate limited, out of retries');
    // Confirmed 2026-08-27: Nominatim's own Retry-After on a 429 here is just "0", not
    // genuine guidance to wait zero seconds - trusting that literally meant every retry
    // fired immediately and just hit another 429, burning through all 5 attempts in
    // under a second. Only a POSITIVE Retry-After is trustworthy; anything else falls
    // back to this script's own exponential backoff instead.
    const retryAfterSec = parseInt(res.headers.get('Retry-After') || '', 10);
    const delayMs = Number.isFinite(retryAfterSec) && retryAfterSec > 0 ? retryAfterSec * 1000 : 5000 * 2 ** attempt;
    console.log(`  rate limited, waiting ${Math.round(delayMs / 1000)}s before retrying...`);
    await new Promise((resolve) => setTimeout(resolve, delayMs));
    return throttledFetch(url, attempt + 1);
  }
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

async function main() {
  const places = await collectPlaces();
  const cache = await loadExistingCache();
  const todo = places.filter((p) => !(normalize(p) in cache));
  console.log(`${places.length} unique places total, ${todo.length} not yet cached.`);

  let done = 0;
  for (const place of todo) {
    const key = normalize(place);
    try {
      const data = await throttledFetch(`https://nominatim.openstreetmap.org/search?format=json&limit=1&q=${encodeURIComponent(place)}`);
      cache[key] = data && data[0]
        ? { lat: parseFloat(data[0].lat), lng: parseFloat(data[0].lon), precision: classifyPrecision(data[0]) }
        : null;
    } catch (err) {
      // Deliberately NOT cache[key] = null here - null means "Nominatim genuinely has
      // no match for this place", a real, useful result worth remembering. A request
      // that failed outright (even after throttledFetch's own retries) is neither that
      // nor a real "found" result - it's just unknown, and leaving the key out of the
      // cache entirely is what makes it show up in `todo` again next time this script
      // runs, instead of a transient failure getting permanently misremembered as "no
      // match" the very first time this hits a bad network moment.
      console.error(`Skipping "${place}" for now (will retry on next run): ${err.message}`);
    }
    done++;
    if (done % 20 === 0 || done === todo.length) {
      console.log(`${done}/${todo.length}`);
      await writeFile(cachePath, serializeCache(cache));
    }
  }
  await writeFile(cachePath, serializeCache(cache));
  console.log('Done. Wrote', cachePath);
}

main();
